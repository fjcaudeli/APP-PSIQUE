-- Conservamos camelCase entre comillas para mantener los contratos actuales.
CREATE TABLE public.usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  email TEXT NOT NULL,
  "passwordHash" TEXT NOT NULL,
  "fechaCreacion" TIMESTAMPTZ(3) NOT NULL,
  CONSTRAINT usuarios_pk PRIMARY KEY (id)
);
CREATE UNIQUE INDEX usuarios_email_unico ON public.usuarios (lower(email));

CREATE TABLE public.pacientes (
  "usuarioId" INTEGER NOT NULL,
  codigo TEXT COLLATE "C" NOT NULL,
  modalidad TEXT NOT NULL,
  estado TEXT NOT NULL,
  "proximaSesion" TEXT,
  frecuencia TEXT NOT NULL,
  "diaHabitual" TEXT,
  "horarioHabitual" TIME WITHOUT TIME ZONE,
  "fechaCreacion" DATE NOT NULL,
  "fechaInicioTratamiento" DATE NOT NULL,
  "motivoConsulta" TEXT NOT NULL,
  "postIt" TEXT NOT NULL,
  CONSTRAINT pacientes_pk PRIMARY KEY ("usuarioId", codigo),
  CONSTRAINT pacientes_usuario_fk FOREIGN KEY ("usuarioId") REFERENCES public.usuarios(id),
  CONSTRAINT pacientes_codigo_check CHECK (
    codigo ~ '^[A-Za-z0-9][A-Za-z0-9_-]{0,11}$' AND lower(codigo) <> 'nuevo'
  ),
  CONSTRAINT pacientes_modalidad_check CHECK (modalidad IN ('Presencial', 'Virtual')),
  CONSTRAINT pacientes_estado_check CHECK (char_length(estado) BETWEEN 1 AND 40),
  CONSTRAINT pacientes_frecuencia_check CHECK (char_length(frecuencia) BETWEEN 1 AND 40),
  CONSTRAINT pacientes_proxima_check CHECK (char_length("proximaSesion") <= 30),
  CONSTRAINT pacientes_dia_check CHECK (
    "diaHabitual" IN ('Lunes', 'Martes', 'Miércoles', 'Jueves', 'Viernes', 'Sábado', 'Domingo')
  ),
  -- TIME admite segundos y 24:00; la aplicación trabaja con minutos entre 00:00 y 23:59.
  CONSTRAINT pacientes_horario_check CHECK (
    "horarioHabitual" < TIME '24:00' AND EXTRACT(SECOND FROM "horarioHabitual") = 0
  ),
  CONSTRAINT pacientes_creacion_check CHECK ("fechaCreacion" BETWEEN DATE '0001-01-01' AND DATE '9999-12-31'),
  CONSTRAINT pacientes_inicio_check CHECK ("fechaInicioTratamiento" BETWEEN DATE '0001-01-01' AND DATE '9999-12-31'),
  CONSTRAINT pacientes_motivo_check CHECK (char_length("motivoConsulta") <= 3000),
  CONSTRAINT pacientes_postit_check CHECK (char_length("postIt") <= 300)
);
CREATE UNIQUE INDEX pacientes_codigo_unico ON public.pacientes ("usuarioId", lower(codigo));

CREATE TABLE public.turnos (
  "usuarioId" INTEGER NOT NULL,
  fecha DATE NOT NULL,
  horario TIME WITHOUT TIME ZONE NOT NULL,
  "codigoPaciente" TEXT COLLATE "C",
  modalidad TEXT,
  estado TEXT NOT NULL,
  CONSTRAINT turnos_pk PRIMARY KEY ("usuarioId", fecha, horario),
  CONSTRAINT turnos_usuario_fk FOREIGN KEY ("usuarioId") REFERENCES public.usuarios(id),
  -- Solo estas referencias se difieren al renombrar un paciente dentro de una transacción.
  CONSTRAINT turnos_paciente_fk FOREIGN KEY ("usuarioId", "codigoPaciente")
    REFERENCES public.pacientes("usuarioId", codigo) ON UPDATE NO ACTION DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT turnos_fecha_check CHECK (fecha BETWEEN DATE '0001-01-01' AND DATE '9999-12-31'),
  CONSTRAINT turnos_horario_check CHECK (horario < TIME '24:00' AND EXTRACT(SECOND FROM horario) = 0),
  CONSTRAINT turnos_modalidad_check CHECK (modalidad IN ('Presencial', 'Virtual')),
  CONSTRAINT turnos_estado_check CHECK (estado IN ('Disponible', 'Programado', 'Liberado')),
  CONSTRAINT turnos_asignacion_check CHECK (
    (estado = 'Programado' AND "codigoPaciente" IS NOT NULL AND modalidad IS NOT NULL)
    OR (estado IN ('Disponible', 'Liberado') AND "codigoPaciente" IS NULL AND modalidad IS NULL)
  )
);

CREATE TABLE public.sesiones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  "usuarioId" INTEGER NOT NULL,
  fecha DATE NOT NULL,
  horario TIME WITHOUT TIME ZONE NOT NULL,
  "codigoPaciente" TEXT COLLATE "C" NOT NULL,
  modalidad TEXT NOT NULL,
  estado TEXT NOT NULL DEFAULT 'Programada',
  "importeCentavos" INTEGER NOT NULL DEFAULT 0,
  "pagadoCentavos" INTEGER NOT NULL DEFAULT 0,
  CONSTRAINT sesiones_pk PRIMARY KEY (id),
  CONSTRAINT sesiones_horario_unico UNIQUE ("usuarioId", fecha, horario),
  CONSTRAINT sesiones_usuario_fk FOREIGN KEY ("usuarioId") REFERENCES public.usuarios(id),
  CONSTRAINT sesiones_paciente_fk FOREIGN KEY ("usuarioId", "codigoPaciente")
    REFERENCES public.pacientes("usuarioId", codigo) ON UPDATE NO ACTION DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT sesiones_turno_fk FOREIGN KEY ("usuarioId", fecha, horario)
    REFERENCES public.turnos("usuarioId", fecha, horario),
  CONSTRAINT sesiones_fecha_check CHECK (fecha BETWEEN DATE '0001-01-01' AND DATE '9999-12-31'),
  CONSTRAINT sesiones_horario_check CHECK (horario < TIME '24:00' AND EXTRACT(SECOND FROM horario) = 0),
  CONSTRAINT sesiones_modalidad_check CHECK (modalidad IN ('Presencial', 'Virtual')),
  CONSTRAINT sesiones_estado_check CHECK (estado IN ('Programada', 'Realizada')),
  CONSTRAINT sesiones_importe_check CHECK ("importeCentavos" BETWEEN 0 AND 999999999),
  CONSTRAINT sesiones_pagado_check CHECK ("pagadoCentavos" BETWEEN 0 AND "importeCentavos")
);
CREATE INDEX sesiones_paciente ON public.sesiones ("usuarioId", "codigoPaciente");

-- Las pruebas usan al propietario de psique_test; no necesitan acceso de psique_app.
-- En desarrollo solo concedemos las operaciones que utiliza la API actual.
DO $$
BEGIN
  IF current_database() = 'psique' THEN
    GRANT SELECT, INSERT, UPDATE ON TABLE
      public.usuarios, public.pacientes, public.turnos, public.sesiones TO psique_app;
    GRANT USAGE ON SEQUENCE public.usuarios_id_seq, public.sesiones_id_seq TO psique_app;
  END IF;
END;
$$;
